CREATE TABLE line (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    number VARCHAR(20) NOT NULL CHECK (length(trim(number)) > 0),
    name VARCHAR(255) NOT NULL CHECK (length(trim(name)) > 0),
    type VARCHAR(50) NOT NULL CHECK (length(trim(type)) > 0),
    color VARCHAR(7) NOT NULL CHECK (color ~ '^#[0-9A-Fa-f]{6}$')
);

CREATE TYPE route_direction AS ENUM ('outbound', 'inbound');

-- One trip pattern of a line; a line runs at most once per direction.
CREATE TABLE route (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    line_id BIGINT NOT NULL REFERENCES line (id) ON DELETE CASCADE,
    direction route_direction NOT NULL,
    UNIQUE (line_id, direction)
);

CREATE TABLE route_stop (
    route_id BIGINT NOT NULL REFERENCES route (id) ON DELETE CASCADE,
    stop_id BIGINT NOT NULL REFERENCES station (id) ON DELETE CASCADE,
    position INTEGER NOT NULL CHECK (position >= 1),
    PRIMARY KEY (route_id, position)
);

CREATE INDEX route_stop_stop_id ON route_stop (stop_id);
