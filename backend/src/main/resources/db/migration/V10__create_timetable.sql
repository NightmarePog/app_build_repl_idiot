-- Stable external references from the assignment data (L001, R00101), so the timetable seed
-- maps by reference instead of guessing from generated ids. The seed (V11) fills them.
ALTER TABLE line ADD COLUMN source_ref VARCHAR(20) UNIQUE
    CONSTRAINT line_source_ref_format CHECK (source_ref ~ '^L[0-9]{3}$');
ALTER TABLE route ADD COLUMN source_ref VARCHAR(20) UNIQUE
    CONSTRAINT route_source_ref_format CHECK (source_ref ~ '^R[0-9]{5}$');

-- Each route stop gets its own identity; a station appears at most once per route.
ALTER TABLE route_stop ADD COLUMN id BIGINT GENERATED BY DEFAULT AS IDENTITY;
ALTER TABLE route_stop ADD CONSTRAINT route_stop_id_key UNIQUE (id);
ALTER TABLE route_stop ADD CONSTRAINT route_stop_id_route_key UNIQUE (id, route_id);
ALTER TABLE route_stop ADD CONSTRAINT route_stop_station_once UNIQUE (route_id, stop_id);

-- A trip is one journey along a route; the route already fixes line, direction and stop order.
CREATE TABLE trip (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    route_id BIGINT NOT NULL REFERENCES route (id) ON DELETE CASCADE,
    source_ref VARCHAR(50) NOT NULL UNIQUE
        CONSTRAINT trip_source_ref_format CHECK (source_ref ~ '^T[0-9]{11}$'),
    -- Lets stop_time prove its stop belongs to this trip's route.
    UNIQUE (id, route_id)
);

CREATE INDEX trip_route_id ON trip (route_id);

-- Times are INTERVALs since midnight of the operating day, so 24:14 (00:14 next day) stays part
-- of the evening trip that left at 23:52; TIME cannot hold that and would need a day column.
CREATE DOMAIN timetable_time AS INTERVAL
    CHECK (VALUE >= INTERVAL '0' AND VALUE < INTERVAL '48 hours'
        AND date_trunc('minute', VALUE) = VALUE);

-- stop_time carries route_id only as the second half of two composite foreign keys: together
-- they prove the route stop belongs to the trip's route. It is not independent data (it always
-- equals trip.route_id, which the trip FK enforces), so it cannot drift; a declarative FK is used
-- instead of a trigger because it cannot be bypassed or forgotten.
CREATE TABLE stop_time (
    trip_id BIGINT NOT NULL,
    route_id BIGINT NOT NULL,
    route_stop_id BIGINT NOT NULL,
    arrival_time timetable_time NOT NULL,
    departure_time timetable_time NOT NULL,
    CONSTRAINT stop_time_pkey PRIMARY KEY (trip_id, route_stop_id),
    CONSTRAINT stop_time_trip_fkey FOREIGN KEY (trip_id, route_id)
        REFERENCES trip (id, route_id) ON DELETE CASCADE,
    -- CASCADE keeps the phase-3 DELETE /stops/{id} working: removing a stop removes its calls,
    -- and the timetable check below drops a trip that is left with fewer than two.
    CONSTRAINT stop_time_route_stop_fkey FOREIGN KEY (route_stop_id, route_id)
        REFERENCES route_stop (id, route_id) ON DELETE CASCADE,
    CONSTRAINT stop_time_arrival_before_departure CHECK (arrival_time <= departure_time)
);

CREATE INDEX stop_time_route_stop ON stop_time (route_stop_id, trip_id);

-- A timetabled route stop keeps its station, route and position.
CREATE FUNCTION route_stop_keep_timetable() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    IF (NEW.stop_id, NEW.route_id, NEW.position) IS DISTINCT FROM (OLD.stop_id, OLD.route_id, OLD.position)
        AND EXISTS (SELECT 1 FROM stop_time WHERE route_stop_id = OLD.id) THEN
        RAISE EXCEPTION 'route stop % has timetabled times and cannot be changed', OLD.id
            USING ERRCODE = 'foreign_key_violation';
    END IF;
    RETURN NEW;
END $$;

CREATE TRIGGER route_stop_keep_timetable BEFORE UPDATE ON route_stop
FOR EACH ROW EXECUTE FUNCTION route_stop_keep_timetable();

-- Checked at commit: a trip has at least two stops, starts on the operating day (its first
-- departure is before 24:00, so later calls may run past midnight but the trip itself never
-- starts on day +1) and never goes back in time. The check runs once per changed row; each run
-- reads only that trip's stop times through stop_time_pkey, so the cost is per trip, not per
-- table, and every change is re-checked even after SET CONSTRAINTS ALL IMMEDIATE.
CREATE FUNCTION trip_check_timetable() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE
    checked BIGINT;
    calls INT;
    first_departure INTERVAL;
BEGIN
    -- Each branch only touches fields its table has; plpgsql resolves record fields lazily.
    IF TG_TABLE_NAME = 'trip' THEN
        checked := NEW.id;
    ELSIF TG_OP = 'DELETE' THEN
        checked := OLD.trip_id;
    ELSE
        checked := NEW.trip_id;
    END IF;
    IF NOT EXISTS (SELECT 1 FROM trip WHERE id = checked) THEN
        RETURN NULL;
    END IF;
    SELECT count(*) INTO calls FROM stop_time WHERE trip_id = checked;
    IF calls < 2 THEN
        IF TG_OP = 'DELETE' THEN
            -- Its stops were removed (phase-3 stop delete); a one-stop trip is no trip.
            DELETE FROM trip WHERE id = checked;
            RETURN NULL;
        END IF;
        RAISE EXCEPTION 'trip % needs at least two stop times', checked
            USING ERRCODE = 'check_violation';
    END IF;
    SELECT st.departure_time INTO first_departure
    FROM stop_time st JOIN route_stop rs ON rs.id = st.route_stop_id
    WHERE st.trip_id = checked ORDER BY rs.position LIMIT 1;
    IF first_departure >= INTERVAL '24 hours' THEN
        RAISE EXCEPTION 'trip % must start before 24:00 of its operating day', checked
            USING ERRCODE = 'check_violation';
    END IF;
    IF EXISTS (
        SELECT 1 FROM (
            SELECT st.arrival_time,
                lag(st.departure_time) OVER (ORDER BY rs.position) AS previous
            FROM stop_time st JOIN route_stop rs ON rs.id = st.route_stop_id
            WHERE st.trip_id = checked
        ) ordered WHERE arrival_time < previous) THEN
        RAISE EXCEPTION 'trip % arrives at a stop before leaving the previous one', checked
            USING ERRCODE = 'check_violation';
    END IF;
    RETURN NULL;
END $$;

CREATE CONSTRAINT TRIGGER trip_check_timetable AFTER INSERT OR UPDATE ON trip
DEFERRABLE INITIALLY DEFERRED FOR EACH ROW EXECUTE FUNCTION trip_check_timetable();
CREATE CONSTRAINT TRIGGER stop_time_check_timetable AFTER INSERT OR UPDATE OR DELETE ON stop_time
DEFERRABLE INITIALLY DEFERRED FOR EACH ROW EXECUTE FUNCTION trip_check_timetable();
